"""Turns Drive an Aerial Vehicle's shipped obstacle map (Data\\map_bin, DAVOB4, MIT, tidusmd) into a 2D height
map: for every 10 m column the top of the highest blocked / danger cell.
  python -I -X utf8 dav_heightmap.py stats
  python -I -X utf8 dav_heightmap.py reds <out HeightMap.reds>
  python -I -X utf8 dav_heightmap.py json <out heights.json>      (for tools\\sim_route.py)
DAVOB4 chunk: 16-byte header ("DAVOB4", zlevels, zmin + 128, cell size in cm as u16, known count u32), then
zlevels slices of 50 x 50 bytes, index (z - zmin) * 2500 + (cy - ccy * 50) * 50 + (cx - ccx * 50).
Cell byte: 0 unknown, 1 clear, 2 danger, 3 blocked. Cell (cx, cy, cz) = floor(world / 10 m).
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
# Folder with Drive an Aerial Vehicle's chunk_*.bin files: <game>\bin\x64\plugins\cyber_engine_tweaks\mods\
# DriveAerialVehicle\Data\map_bin of your own install. Set the environment variable DAV_MAP_DIR.
MAP = os.environ.get('DAV_MAP_DIR', '')
if not os.path.isdir(MAP):
    sys.exit('Set DAV_MAP_DIR to the Data\\map_bin folder of your Drive an Aerial Vehicle install.')
CH = 50
BS = chr(92)


def load():
    """{(ccx, ccy): list of 2500 (known, top_blocked_m, top_danger_m)}"""
    out = {}
    for name in sorted(os.listdir(MAP)):
        m = re.match(r'chunk_(-?\d+)_(-?\d+)\.bin$', name)
        if not m:
            continue
        raw = open(os.path.join(MAP, name), 'rb').read()
        if raw[:6] != b'DAVOB4':
            continue
        zlev, zmin = raw[6], raw[7] - 128
        cell_cm = raw[8] + raw[9] * 256
        assert cell_cm in (0, 1000), cell_cm
        body = raw[16:]
        cols = []
        for i in range(CH * CH):
            col = body[i::CH * CH][:zlev]
            known = any(col)
            top_b = top_d = None
            for lz in range(len(col) - 1, -1, -1):
                if col[lz] == 3 and top_b is None:
                    top_b = (zmin + lz + 1) * 10
                if col[lz] >= 2 and top_d is None:
                    top_d = (zmin + lz + 1) * 10
                if top_b is not None:
                    break
            cols.append((known, top_b, top_d))
        out[(int(m.group(1)), int(m.group(2)))] = cols
    return out


def codes(cols):
    """Per column: 10-98 = 10 + top of the highest blocked or danger cell in 10 m units, 99 = nothing known."""
    out = []
    for k, b, d in cols:
        if not k:
            out.append(99)
        else:
            top = d if d is not None else 0
            out.append(10 + min(88, max(0, top // 10)))
    return out


def stats():
    chunks = load()
    xs = [c[0] for c in chunks]
    ys = [c[1] for c in chunks]
    print('chunks', len(chunks), 'x', min(xs), max(xs), 'y', min(ys), max(ys),
          '-> world x %d..%d m, y %d..%d m' % (min(xs) * 500, (max(xs) + 1) * 500, min(ys) * 500, (max(ys) + 1) * 500))
    tot = known = blocked = 0
    hist = {}
    for cols in chunks.values():
        for k, b, d in cols:
            tot += 1
            known += 1 if k else 0
            if b is not None:
                blocked += 1
                hist[b // 50 * 50] = hist.get(b // 50 * 50, 0) + 1
    print('columns %d, with any known cell %d (%.0f %%), with a blocked cell %d' % (tot, known, 100.0 * known / tot, blocked))
    for h in sorted(hist):
        print('  top %4d-%4d m: %6d columns' % (h, h + 49, hist[h]))
    for cy in range(max(ys), min(ys) - 1, -1):
        row = ''
        for cx in range(min(xs), max(xs) + 1):
            cols = chunks.get((cx, cy))
            if cols is None:
                row += ' .'
            else:
                frac = sum(1 for k, b, d in cols if k) / 2500.0
                row += ' %d' % min(9, int(frac * 10))
        print('  y%3d %s' % (cy, row))


def reds(path):
    chunks = load()
    lines = [
        '// Cyberslop AV Flight 1.0.0 - building heights for the autopilot. GENERATED by tools' + BS + 'dav_heightmap.py from the',
        '// obstacle map shipped with Drive an Aerial Vehicle 3.5.0 (Data' + BS + 'map_bin, MIT License, Copyright (C) 2024 tidusmd).',
        '// 10 m columns in 500 m chunks (chunk = floor(world / 500), column = floor(world / 10)). Two digits per column,',
        '// row by row (index (cy - chunkY * 50) * 50 + (cx - chunkX * 50)): 10-98 = 10 + top of the highest blocked or',
        '// danger cell in 10 m units above sea level, 99 = nothing known about that column.',
        'module CyberslopAVFlight',
        '',
        'public abstract class AVFHeightData {',
        '  public final static func Chunk(cx: Int32, cy: Int32) -> String {',
    ]
    for (cx, cy) in sorted(chunks):
        digits = ''.join('%02d' % c for c in codes(chunks[(cx, cy)]))
        lines.append('    if cx == %d && cy == %d { return "%s"; };' % (cx, cy, digits))
    lines += ['    return "";', '  }', '}', '']
    tmp = path + '.tmp'
    with open(tmp, 'w', encoding='utf-8', newline='\n') as fh:
        fh.write('\n'.join(lines))
    os.replace(tmp, path)
    print('wrote %s: %d chunks, %d bytes' % (path, len(chunks), os.path.getsize(path)))


def to_json(path):
    chunks = load()
    data = {'%d,%d' % k: codes(v) for k, v in chunks.items()}
    tmp = path + '.tmp'
    with open(tmp, 'w', encoding='utf-8') as fh:
        json.dump(data, fh)
    os.replace(tmp, path)
    print('wrote %s: %d chunks' % (path, len(data)))


if __name__ == '__main__':
    mode = sys.argv[1] if len(sys.argv) > 1 else 'stats'
    if mode == 'reds':
        reds(sys.argv[2])
    elif mode == 'json':
        to_json(sys.argv[2])
    else:
        stats()
